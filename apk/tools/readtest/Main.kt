import net.koma.reader.ReadEngine

fun main() {
    val e = ReadEngine()
    val R = ReadEngine.Rules(dir = "rtl")
    fun L(t: String, l: Double, top: Double, r: Double, b: Double) = ReadEngine.Line(t, l, top, r, b, 0.9)

    // Страница из скриншота 22:41: два облачка рядом и одно ниже.
    // Левое облачко: 4 строки, разбитые на два куска («ВЫСО-» + «ЧЕСТВО»).
    val story = listOf(
        L("УЖЕ ПОРА НА-", 0.14, 0.10, 0.42, 0.13),
        L("ЧИНАТЬ ВСТРЕЧУ,", 0.14, 0.14, 0.44, 0.17),
        L("ТАК ЧТО ЕЁ ВЫСО-", 0.14, 0.18, 0.45, 0.21),
        L("-ЧЕСТВО, ДОЛЖНО", 0.14, 0.22, 0.44, 0.25),
        L("БЫТЬ, ПРИБЫЛА.", 0.14, 0.26, 0.42, 0.29),
        // Правое облачко — выше по странице, но правее: в манге читается первым.
        L("НЕ УВЕРЕН,", 0.58, 0.22, 0.86, 0.25),
        L("КАК СТОИТ СКА-", 0.58, 0.26, 0.87, 0.29),
        L("ЗАТЬ ЭТО, НО...", 0.58, 0.30, 0.86, 0.33),
        // Нижнее облачко.
        L("В БУДУЩЕМ,", 0.14, 0.62, 0.44, 0.65),
        L("КОГДА ВЫ БУДЕ-", 0.14, 0.66, 0.45, 0.69),
        L("ТЕ ГОВОРИТЬ С ЕЁ", 0.14, 0.70, 0.47, 0.73),
        L("ВЫСОЧЕСТВОМ.", 0.14, 0.74, 0.45, 0.77),
    )
    val plan = e.plan(story, R)
    println("реплик: ${plan.size}")
    plan.forEachIndexed { i, o -> println("  ${i + 1}. ${o.optString("text")}") }

    // ── Тонкая полоска-обрывок от детектора (нашлось в эмуляторе APKForge) ──
    // Детектор отдал рамку высотой 0,002 страницы поперёк картинки с мусорным
    // текстом. Раньше её высота занижала «типичную высоту строки», и вторая
    // строка первого облачка НЕ приклеивалась — одна реплика выходила двумя
    // текстами, а в первый кусок попадал мусор.
    val withSliver = story + listOf(
        L("так что сё выио шблтоо", 0.13, 0.1290, 0.86, 0.1310),   // толщина 0,002
    )
    val planSliver = e.plan(withSliver, R)
    println("с полоской-обрывком реплик: ${planSliver.size}")
    planSliver.forEachIndexed { i, o -> println("  ${i + 1}. ${o.optString("text")}") }
    val okSliver = planSliver.size == 3
        && planSliver.none { it.optString("text").contains("шблтоо") }
        && planSliver[1].optString("text").contains("ПРИБЫЛА")
    println(if (okSliver) "ПОЛОСКА-ОБРЫВОК: реплика не разрезана и мусор не попал"
          else "ПОЛОСКА-ОБРЫВОК: ПЛОХО — реплика разрезана или мусор в тексте")

    // Полосы: страница 4000 px, экран 1000 px.
    println("полос (4000/1000): " + e.bands(4000.0, 1000.0, R).length())
    println("полос (страница по экрану): " + e.bands(800.0, 1000.0, R).length())
    // ── Страница 1 «Пиксель хоррор» (телефон, 4.11, v1.9.64) ──────────────
    // Вопрос: почему из «ШКОЛУ?» вышло «ШКОЛ?». Строки — как их отдал движок.
    val page1 = listOf(
        L("А ПОЧЕМУ",       0.30, 0.10, 0.52, 0.13),
        L("ТЫ ПЕРЕВЕ-",     0.30, 0.14, 0.55, 0.17),
        L("ЛАСЬ В НАШУ",    0.30, 0.18, 0.55, 0.21),
        L("ШКОЛУ?",         0.30, 0.22, 0.50, 0.25),
        L("ЭЙ,",            0.80, 0.10, 0.90, 0.13),
        L("МИЧИРУЯ,",       0.78, 0.14, 0.93, 0.17),
        L("ТЫ ТУТ ПО-",     0.78, 0.18, 0.93, 0.21),
        L("ДУМАЛАw",        0.78, 0.22, 0.93, 0.25),
        L("ого,",           0.22, 0.62, 0.30, 0.65),
        L("ПОХОЖЕ",         0.22, 0.66, 0.34, 0.69),
        L("ТЫ ОЧЕНЬ",       0.22, 0.70, 0.36, 0.73),
        L("ЗАНЯТА!",        0.22, 0.74, 0.34, 0.77),
        L("ИЗ-ЗА",          0.80, 0.62, 0.90, 0.65),
        L("РАБОТЫ.",        0.80, 0.66, 0.92, 0.69),
    )
    val plan1 = e.plan(page1, R)
    println("страница 1: реплик ${plan1.size}")
    plan1.forEachIndexed { i, o -> println("  ${i + 1}. ${o.optString("text")}") }

}
